let num1 = parseFloat(prompt("Digite um numero"))
let num2 = parseFloat(prompt("Digite um numero"))
let op = prompt("Selecione o operador (+, -, * ou /).")

if (op == "+"){
    alert(num1 + num2)
}else if (op == "-"){
    alert(num1 - num2)
}else if (op == "*"){
    alert(num1 * num2)
}else if (op == "/"){
    alert(num1 / num2)
}